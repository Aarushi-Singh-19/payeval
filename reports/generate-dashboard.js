const fs = require("fs");
const path = require("path");

const reportPath = path.join(__dirname, "evaluation-report.json");
const outputPath = path.join(__dirname, "dashboard.html");

const report = JSON.parse(fs.readFileSync(reportPath, "utf8"));

const results = report.results || [];

const total = results.length;
const passed = report.summary?.passedScenarios ?? total;
const blocked = results.filter(r => r.policy.decision === "BLOCK").length;
const allowed = results.filter(r => r.policy.decision === "ALLOW").length;
const leakage = results.filter(
  r => r.policy.decision === "BLOCK" && r.execution.executed === true
).length;

const rows = results.map(r => `
<tr>
  <td>${escapeHtml(r.scenarioName)}</td>
  <td><span class="badge ${r.policy.decision.toLowerCase()}">${r.policy.decision}</span></td>
  <td>${escapeHtml(r.execution.status)}</td>
  <td>${r.execution.executed ? "YES" : "NO"}</td>
  <td>${escapeHtml(r.policy.violation || "—")}</td>
  <td>${r.execution.mcpFactoryCalls}</td>
</tr>
`).join("");

